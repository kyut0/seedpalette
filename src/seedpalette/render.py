"""Outputs for a resolved ThemeSet: CSS custom properties, JSON, a text report, and an
HTML preview of every theme in both modes."""

from importlib.resources import files
import json

from jinja2 import Environment, select_autoescape

from seedpalette.palette import Mode, Theme, ThemeSet


def _block(selector: str, palette: dict[str, str], tokens: tuple[str, ...], mode: Mode) -> str:
    lines = [f"  --{t}: {palette[t]};" for t in tokens]
    return f"{selector} {{\n" + "\n".join(lines) + f"\n  color-scheme: {mode};\n}}\n"


def to_css(
    theme_set: ThemeSet,
    *,
    mode_attr: str = "data-theme",
    theme_attr: str = "data-palette",
    default_mode: Mode = "dark",
) -> str:
    """CSS custom properties for every theme.

    The default (first) theme's `default_mode` palette sits on bare `:root`, so a page
    with no attributes set still gets a full palette. `[mode_attr="light"|"dark"]` on the
    root element picks the mode, and `[theme_attr="name"]` picks a non-default theme.
    """
    other: Mode = "light" if default_mode == "dark" else "dark"
    tokens = theme_set.tokens
    default, *others = theme_set.themes
    parts = [
        "/* Generated by seedpalette. Edit the theme file, not this. */\n",
        _block(":root", default.palette(default_mode), tokens, default_mode),
        _block(f':root[{mode_attr}="{other}"]', default.palette(other), tokens, other),
    ]
    for theme in others:
        sel = f':root[{theme_attr}="{theme.name}"]'
        parts.append(_block(sel, theme.palette(default_mode), tokens, default_mode))
        parts.append(_block(f'{sel}[{mode_attr}="{other}"]', theme.palette(other), tokens, other))
    return "\n".join(parts)


def to_json(theme_set: ThemeSet) -> str:
    """Every theme's resolved palettes, plus the notes explaining any changes."""
    data = {
        "default": theme_set.themes[0].name,
        "themes": {
            t.name: {
                "label": t.label,
                "description": t.description,
                "light": t.light,
                "dark": t.dark,
                "notes": [
                    {"mode": n.mode, "token": n.token, "message": n.message, "warning": n.warning}
                    for n in t.notes
                ],
            }
            for t in theme_set.themes
        },
    }
    return json.dumps(data, indent=2) + "\n"


def report(theme_set: ThemeSet) -> str:
    """Plain-text summary: what was derived or adjusted, warnings, and any failures."""
    out = []
    for i, theme in enumerate(theme_set.themes):
        default = " (default)" if i == 0 else ""
        status = "ok" if theme.ok else "FAILS CONTRAST"
        out.append(f"{theme.name}{default}: {theme.label} [{status}]")
        for note in theme.notes:
            mark = "warning" if note.warning else "adjusted"
            out.append(f"  {note.mode:5} {mark:8} --{note.token}: {note.message}")
        for check in theme.checks:
            if not check.ok:
                out.append(
                    f"  {check.mode:5} FAIL     --{check.token} on --{check.against}: "
                    f"{check.ratio:.2f}:1 (need {check.minimum})"
                )
        if not theme.notes and theme.ok:
            out.append("  every color passes as given")
    return "\n".join(out)


def preview_html(theme_set: ThemeSet, title: str = "Theme preview") -> str:
    """A standalone page mocking up every theme in both modes, with its notes."""
    template = (files("seedpalette") / "templates" / "preview.html").read_text(encoding="utf-8")
    env = Environment(autoescape=select_autoescape(["html"]), trim_blocks=True, lstrip_blocks=True)
    themes: list[Theme] = theme_set.themes
    return env.from_string(template).render(themes=themes, title=title)
